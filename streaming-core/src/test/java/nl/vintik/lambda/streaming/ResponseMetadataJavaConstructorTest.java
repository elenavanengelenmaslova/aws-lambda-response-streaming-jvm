package nl.vintik.lambda.streaming;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.Map;
import kotlinx.serialization.json.Json;
import kotlinx.serialization.json.JsonElement;
import kotlinx.serialization.json.JsonObject;
import kotlinx.serialization.json.JsonPrimitive;
import org.junit.jupiter.api.Test;

/**
 * Proves the two-argument {@link ResponseMetadata} constructor (generated by
 * {@code @JvmOverloads}) is usable from plain Java and survives the wire protocol.
 */
class ResponseMetadataJavaConstructorTest {

    private static final int DELIMITER_LEN = 8;

    @Test
    void givenTwoArgConstructorWhenWrittenThroughResponseWriterThenStatusAndHeadersRoundTripWithoutCookies()
            throws IOException {
        Map<String, String> headers = Map.of("Content-Type", "text/event-stream");
        ResponseMetadata metadata = new ResponseMetadata(200, headers);
        ByteArrayOutputStream out = new ByteArrayOutputStream();

        new ResponseWriter().writeMetadata(out, metadata);

        byte[] bytes = out.toByteArray();
        int delimiterAt = indexOfDelimiter(bytes);
        assertNotEquals(-1, delimiterAt, "delimiter must be present");
        assertEquals(bytes.length, delimiterAt + DELIMITER_LEN, "nothing may follow the delimiter");

        String json = new String(Arrays.copyOfRange(bytes, 0, delimiterAt), StandardCharsets.UTF_8);
        JsonElement parsed = Json.Default.parseToJsonElement(json);
        JsonObject root = (JsonObject) parsed;

        assertEquals("200", ((JsonPrimitive) root.get("statusCode")).getContent());
        JsonObject decodedHeaders = (JsonObject) root.get("headers");
        assertEquals(1, decodedHeaders.size());
        assertEquals("text/event-stream", ((JsonPrimitive) decodedHeaders.get("Content-Type")).getContent());
        assertFalse(root.containsKey("cookies"), "cookies must not be emitted when null");
    }

    @Test
    void givenTwoArgConstructorThenCookiesDefaultsToNull() {
        ResponseMetadata metadata = new ResponseMetadata(204, Map.of());

        assertEquals(204, metadata.getStatusCode());
        assertEquals(Map.of(), metadata.getHeaders());
        assertNull(metadata.getCookies());
    }

    private static int indexOfDelimiter(byte[] bytes) {
        for (int i = 0; i + DELIMITER_LEN <= bytes.length; i++) {
            boolean allZero = true;
            for (int j = 0; j < DELIMITER_LEN; j++) {
                if (bytes[i + j] != 0) {
                    allZero = false;
                    break;
                }
            }
            if (allZero) {
                return i;
            }
        }
        return -1;
    }
}
