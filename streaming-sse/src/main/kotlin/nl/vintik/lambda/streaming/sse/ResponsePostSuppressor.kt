package nl.vintik.lambda.streaming.sse

import org.objectweb.asm.ClassReader
import org.objectweb.asm.ClassVisitor
import org.objectweb.asm.ClassWriter
import org.objectweb.asm.Label
import org.objectweb.asm.MethodVisitor
import org.objectweb.asm.Opcodes
import java.lang.instrument.ClassFileTransformer
import java.security.ProtectionDomain

/**
 * Patches the one runtime method that would post a second response for an invocation
 * [StreamingResponse] has already answered.
 *
 * Target, read off the deployed runtime interface client rather than from published source — the
 * method is `reportInvocationSuccess`, not the `postInvocationResponse` the GitHub sources suggest:
 * ```
 * com.amazonaws.services.lambda.runtime.api.client.runtimeapi.LambdaRuntimeApiClientImpl
 *     void reportInvocationSuccess(String requestId, byte[] response, String xrayHeader)
 * ```
 *
 * The injected prologue is the whole intervention:
 * ```java
 * if (StreamingState.alreadyAnswered()) return;
 * ```
 *
 * Everything else is left byte-identical — `nextInvocation`, `restoreNext` (the SnapStart restore
 * hook), error reporting, and the CRaC coordination AWS's loop performs. That is deliberate: an
 * earlier approach replaced the whole invocation loop and silently stopped CRaC `beforeCheckpoint`
 * hooks from firing, so SnapStart priming stopped working with no error anywhere.
 *
 * **Fails safe.** Any failure leaves the class untouched, so the function keeps working on AWS's
 * normal buffered path. [StreamingAgent.isPatched] reports whether the patch landed and
 * [StreamingResponse] refuses to stream when it did not, so a runtime change surfaces as one clear
 * error instead of a failed invocation per request.
 */
internal object ResponsePostSuppressor : ClassFileTransformer {

    /** Internal (slash-separated) name of the class to patch. */
    const val TARGET_CLASS: String =
        "com/amazonaws/services/lambda/runtime/api/client/runtimeapi/LambdaRuntimeApiClientImpl"

    /** Name of the method that posts a successful invocation response. */
    const val TARGET_METHOD: String = "reportInvocationSuccess"

    private val STATE_CLASS: String = StreamingState::class.java.name.replace('.', '/')
    private const val GUARD_METHOD = "alreadyAnswered"
    private const val GUARD_DESCRIPTOR = "()Z"

    /** Operand stack slots the injected guard needs. */
    private const val GUARD_STACK_SLOTS = 1

    @Volatile
    private var applied = false

    /** True once the patch has been applied to the real runtime class. */
    fun isApplied(): Boolean = applied

    override fun transform(
        loader: ClassLoader?,
        className: String?,
        classBeingRedefined: Class<*>?,
        protectionDomain: ProtectionDomain?,
        classfileBuffer: ByteArray?,
    ): ByteArray? {
        if (className != TARGET_CLASS || classfileBuffer == null) return null
        return runCatching { patch(classfileBuffer) }
            .onSuccess { patched ->
                applied = true
                log("patched $TARGET_METHOD (${classfileBuffer.size} -> ${patched.size} bytes)")
            }
            .onFailure { e ->
                log("could not patch $TARGET_METHOD, leaving the class untouched: ${e::class.java.name}: ${e.message}")
            }
            .getOrNull()
    }

    /**
     * Returns [original] with the guard prepended to every [TARGET_METHOD] body.
     *
     * Visible for testing against a synthetic class, so the generated bytecode is verified without
     * a Lambda runtime.
     *
     * @throws IllegalStateException if no such method exists, which means the runtime changed and
     *   the patch must not be reported as applied.
     */
    internal fun patch(original: ByteArray): ByteArray {
        val reader = ClassReader(original)
        val writer = ClassWriter(reader, 0)
        var matched = 0

        reader.accept(
            object : ClassVisitor(Opcodes.ASM9, writer) {
                override fun visitMethod(
                    access: Int,
                    name: String?,
                    descriptor: String?,
                    signature: String?,
                    exceptions: Array<out String>?,
                ): MethodVisitor? {
                    val delegate = super.visitMethod(access, name, descriptor, signature, exceptions)
                    if (name != TARGET_METHOD || delegate == null) return delegate
                    matched++
                    return GuardingMethodVisitor(delegate)
                }
            },
            0,
        )

        check(matched > 0) { "no method named $TARGET_METHOD found in $TARGET_CLASS" }
        return writer.toByteArray()
    }

    /**
     * Emits `if (StreamingState.alreadyAnswered()) return;` before the original body.
     *
     * Two details are load-bearing, and the JVM verifier rejects the class without them:
     *  - a branch target in a class file of version 50 or later needs a **stack map frame**. At
     *    `carryOn` the operand stack is empty and the locals are exactly the method's parameters,
     *    i.e. unchanged from method entry, so `F_SAME` describes it precisely. Emitting it by hand
     *    keeps `COMPUTE_FRAMES` out of the picture, which would otherwise have to resolve the
     *    runtime's own class hierarchy to merge frames.
     *  - the guard pushes one value, so `maxStack` must be at least 1 even if the original body
     *    needed none.
     */
    private class GuardingMethodVisitor(delegate: MethodVisitor) :
        MethodVisitor(Opcodes.ASM9, delegate) {

        override fun visitCode() {
            super.visitCode()
            val carryOn = Label()
            visitMethodInsn(Opcodes.INVOKESTATIC, STATE_CLASS, GUARD_METHOD, GUARD_DESCRIPTOR, false)
            visitJumpInsn(Opcodes.IFEQ, carryOn)
            visitInsn(Opcodes.RETURN)
            visitLabel(carryOn)
            visitFrame(Opcodes.F_SAME, 0, null, 0, null)
        }

        override fun visitMaxs(maxStack: Int, maxLocals: Int) {
            super.visitMaxs(maxStack.coerceAtLeast(GUARD_STACK_SLOTS), maxLocals)
        }
    }

    /** stderr: this runs in `premain`, before any logging backend is configured. */
    private fun log(message: String) = System.err.println("$AGENT_LOG_PREFIX $message")
}

/** Prefix on every agent log line, so the setup is greppable in CloudWatch. */
internal const val AGENT_LOG_PREFIX: String = "[streaming-sse-agent]"
