package nl.vintik.lambda.streaming.sse

import org.junit.jupiter.api.AfterEach
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNull
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Test
import org.objectweb.asm.ClassWriter
import org.objectweb.asm.Opcodes

/**
 * Verifies the bytecode patch against a **synthetic** stand-in for the Lambda runtime's
 * `LambdaRuntimeApiClientImpl`, generated here with the same method name and descriptor.
 *
 * This is the test that matters most for the agent: the patched class is loaded by the JVM, so the
 * verifier rejects invalid bytecode outright, and the counter proves the guard actually
 * short-circuits rather than merely being present.
 *
 * The real class is never involved, so [ResponsePostSuppressor.isApplied] — which reports whether
 * the live runtime was patched — stays untouched by these tests.
 */
class ResponsePostSuppressorTest {

    @AfterEach
    fun clear() {
        StreamingState.reset()
        Counter.calls = 0
    }

    /** Counts bodies that actually ran; the patched method increments it. */
    object Counter {
        @JvmStatic
        var calls: Int = 0

        @JvmStatic
        fun record() {
            calls++
        }
    }

    /**
     * Builds `public class Stand In { public void reportInvocationSuccess(String, byte[], String)
     * { Counter.record(); } }` — same name and descriptor as the method the agent patches.
     */
    private fun syntheticClass(internalName: String): ByteArray {
        val writer = ClassWriter(0)
        writer.visit(
            Opcodes.V21,
            Opcodes.ACC_PUBLIC,
            internalName,
            null,
            "java/lang/Object",
            null,
        )
        writer.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null).apply {
            visitCode()
            visitVarInsn(Opcodes.ALOAD, 0)
            visitMethodInsn(Opcodes.INVOKESPECIAL, "java/lang/Object", "<init>", "()V", false)
            visitInsn(Opcodes.RETURN)
            visitMaxs(1, 1)
            visitEnd()
        }
        val descriptor = "(Ljava/lang/String;[BLjava/lang/String;)V"
        writer.visitMethod(Opcodes.ACC_PUBLIC, ResponsePostSuppressor.TARGET_METHOD, descriptor, null, null).apply {
            visitCode()
            visitMethodInsn(
                Opcodes.INVOKESTATIC,
                Counter::class.java.name.replace('.', '/'),
                "record",
                "()V",
                false,
            )
            visitInsn(Opcodes.RETURN)
            visitMaxs(1, 4)
            visitEnd()
        }
        writer.visitEnd()
        return writer.toByteArray()
    }

    /** Loads one class from bytes, delegating everything else to the test class loader. */
    private class SingleClassLoader(
        private val name: String,
        private val bytes: ByteArray,
    ) : ClassLoader(ResponsePostSuppressorTest::class.java.classLoader) {
        override fun findClass(requested: String): Class<*> =
            if (requested == name) defineClass(requested, bytes, 0, bytes.size) else super.findClass(requested)
    }

    private fun loadPatched(simpleName: String): Pair<Any, java.lang.reflect.Method> {
        val binaryName = "nl.vintik.generated.$simpleName"
        val patched = ResponsePostSuppressor.patch(syntheticClass(binaryName.replace('.', '/')))
        val type = SingleClassLoader(binaryName, patched).loadClass(binaryName)
        val method = type.getDeclaredMethod(
            ResponsePostSuppressor.TARGET_METHOD,
            String::class.java,
            ByteArray::class.java,
            String::class.java,
        )
        return type.getDeclaredConstructor().newInstance() to method
    }

    @Test
    fun `Given the invocation is not answered When the patched method runs Then the original body still executes`() {
        val (instance, method) = loadPatched("NotAnswered")
        StreamingState.reset()

        method.invoke(instance, "req", ByteArray(0), null)

        assertEquals(1, Counter.calls, "AWS's own post must still happen when nothing was streamed")
    }

    @Test
    fun `Given the invocation was already answered When the patched method runs Then the body is skipped`() {
        val (instance, method) = loadPatched("AlreadyAnswered")
        StreamingState.markAnswered()

        method.invoke(instance, "req", ByteArray(0), null)

        assertEquals(0, Counter.calls, "a duplicate post is what causes Runtime.ExitError")
    }

    @Test
    fun `Given a patched class When it is loaded Then the JVM verifier accepts the generated bytecode`() {
        // loadClass itself would throw VerifyError on invalid bytecode; invoking both paths covers
        // the inserted branch and the fall-through.
        val (instance, method) = loadPatched("Verifiable")

        StreamingState.markAnswered()
        method.invoke(instance, "a", ByteArray(1), "b")
        StreamingState.reset()
        method.invoke(instance, "a", ByteArray(1), "b")

        assertEquals(1, Counter.calls)
    }

    @Test
    fun `Given a class without the target method When patching Then it fails rather than silently reporting success`() {
        val writer = ClassWriter(0)
        writer.visit(Opcodes.V21, Opcodes.ACC_PUBLIC, "nl/vintik/generated/NoMethod", null, "java/lang/Object", null)
        writer.visitEnd()

        val failure = assertThrows(IllegalStateException::class.java) {
            ResponsePostSuppressor.patch(writer.toByteArray())
        }

        assertEquals(true, failure.message?.contains(ResponsePostSuppressor.TARGET_METHOD))
    }

    @Test
    fun `Given a class that is not the target When the transformer sees it Then it is left untouched`() {
        val result = ResponsePostSuppressor.transform(
            null,
            "com/example/Unrelated",
            null,
            null,
            syntheticClass("com/example/Unrelated"),
        )

        assertNull(result, "returning null leaves the class byte-identical")
    }

    @Test
    fun `Given unparseable bytes for the target class When the transformer runs Then it fails safe and leaves the class untouched`() {
        val result = ResponsePostSuppressor.transform(
            null,
            ResponsePostSuppressor.TARGET_CLASS,
            null,
            null,
            byteArrayOf(1, 2, 3),
        )

        assertNull(result, "a broken patch must not break the function; it must fall back to buffered")
    }
}
